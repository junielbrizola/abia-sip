package sip

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"strings"

	"go.opentelemetry.io/otel/trace"
)

// newABIATraceContext creates a W3C-compatible trace ID stable for the SIP
// dialog. The server-generated local tag prevents caller-controlled Call-ID
// values from choosing or colliding with the correlation ID.
func newABIATraceContext(call *sipInbound) (string, trace.SpanContext, error) {
	if call == nil || call.sipCallID == "" || call.tag == "" || call.id == "" {
		return "", trace.SpanContext{}, errors.New("SIP dialog identity is incomplete")
	}
	dialogIdentity := "abia-sip-dialog-v1\x00" + call.sipCallID + "\x00" + string(call.tag) + "\x00" + string(call.id)
	digest := sha256.Sum256([]byte(dialogIdentity))
	var traceID trace.TraceID
	var spanID trace.SpanID
	copy(traceID[:], digest[:16])
	if !traceID.IsValid() {
		traceID[len(traceID)-1] = 1
	}
	// Keep this context available to the inbound-call consumer even if the
	// process entropy source is unavailable. The server-generated local tag is
	// part of the dialog identity, so deriving the span ID from the second half
	// of the digest remains bound to this SIP dialog.
	copy(spanID[:], digest[16:24])
	if !spanID.IsValid() {
		spanID[len(spanID)-1] = 1
	}
	spanContext := trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    traceID,
		SpanID:     spanID,
		TraceFlags: trace.FlagsSampled,
	})
	return traceID.String(), spanContext, nil
}

// abiaCallIDFromRoomName extracts an application UUID only from the room-name
// format generated by the Core telephony adapter.
func abiaCallIDFromRoomName(roomName string) string {
	const prefix = "vh-"
	if !strings.HasPrefix(roomName, prefix) {
		return ""
	}
	raw := strings.TrimPrefix(roomName, prefix)
	if len(raw) != 32 {
		return ""
	}
	if _, err := hex.DecodeString(raw); err != nil {
		return ""
	}
	return raw[:8] + "-" + raw[8:12] + "-" + raw[12:16] + "-" + raw[16:20] + "-" + raw[20:]
}
